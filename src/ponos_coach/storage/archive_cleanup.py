"""Removal of the GPX files that profiles created before the FIT-only change left in the archive.

Used after the schema migration that drops GPX activities from the database: the database is
already committed, so a file that stays behind is a harmless orphan. A path that does not have
the exact archive shape (`<year>/<sha256>.gpx`, generated by the program) is never touched, and
a link is never followed: only a regular file inside the archive folder is removed.
"""

from __future__ import annotations

import os
import re
import stat
from collections.abc import Iterable
from pathlib import Path
from typing import Final

_GPX_PATH: Final = re.compile(r"[0-9]{4}/[0-9a-f]{64}\.gpx")
_REPARSE_POINT: Final = 0x400  # FILE_ATTRIBUTE_REPARSE_POINT


def _is_plain_file(status: os.stat_result) -> bool:
    attributes = int(getattr(status, "st_file_attributes", 0))
    return stat.S_ISREG(status.st_mode) and not attributes & _REPARSE_POINT


def remove_gpx_files(archive_root: Path, relative_paths: Iterable[str]) -> int:
    """Remove the listed GPX files from the archive and return how many were removed.

    A missing file, a path of another shape, a link or an I/O error does not stop the others:
    the file stays (or was not there) and nothing more is lost.
    """
    removed = 0
    for relative in relative_paths:
        if not _GPX_PATH.fullmatch(relative):
            continue
        year, name = relative.split("/")
        path = archive_root / year / name
        try:
            if _is_plain_file(path.lstat()) and not (archive_root / year).is_symlink():
                path.unlink()
                removed += 1
        except OSError:
            continue
    return removed
