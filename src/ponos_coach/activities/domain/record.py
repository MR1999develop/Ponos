"""Row of the activity index and reference to the original file in the archive."""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import datetime
from enum import Enum
from pathlib import PurePosixPath

from ponos_coach.activities.domain.activity import Activity
from ponos_coach.activities.domain.identity import ActivityIdentity, FileFormat
from ponos_coach.activities.domain.sport import Sport
from ponos_coach.activities.domain.summary import ActivitySummary
from ponos_coach.activities.domain.timing import check_durations, check_utc

_SHA256_HEX = re.compile(r"[0-9a-f]{64}")
_ARCHIVE_PART = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]{0,127}")
_MAX_ARCHIVE_PARTS = 8


@dataclass(frozen=True, slots=True)
class ArchivedFile:
    """Original file in the archive: relative path generated by the program, SHA-256, bytes.

    `relative_path` is relative to the archive folder, with `/` as separator, made of
    at most 8 components of characters `A-Za-z0-9._-` (never `..`, absolute or with `\\`):
    no external data ever enters a file name. `sha256_hex` has 64 lowercase digits.
    """

    relative_path: PurePosixPath
    sha256_hex: str
    size_bytes: int

    def __post_init__(self) -> None:
        parts = self.relative_path.parts
        if not parts or len(parts) > _MAX_ARCHIVE_PARTS or self.relative_path.is_absolute():
            raise ValueError("archive path empty, too deep or absolute")
        if not all(_ARCHIVE_PART.fullmatch(p) and not p.endswith(".") for p in parts):
            raise ValueError("archive path with disallowed components")
        if not _SHA256_HEX.fullmatch(self.sha256_hex):
            raise ValueError("the SHA-256 must be 64 lowercase hexadecimal digits")
        if self.size_bytes < 0:
            raise ValueError("the size cannot be negative")


class ActivityOrigin(Enum):
    """How the activity entered the profile. The value is stable (saved data)."""

    IMPORT = "import"
    GARMIN = "garmin"


@dataclass(frozen=True, slots=True)
class ActivityRecord:
    """A row of the index: what is needed to list, filter and find the file again.

    Invariants: `file_format` is that of the identity; start and `imported_at` in UTC; durations
    finite and positive with `timer_s <= elapsed_s`; with origin `GARMIN` the Garmin id is present
    and
    positive (an activity imported from file may receive it later, if matched).
    """

    identity: ActivityIdentity
    file_format: FileFormat
    sport: Sport
    start: datetime
    elapsed_s: float
    timer_s: float
    summary: ActivitySummary
    archived: ArchivedFile
    origin: ActivityOrigin
    imported_at: datetime
    garmin_activity_id: int | None = None

    def __post_init__(self) -> None:
        check_utc(self.start)
        check_utc(self.imported_at)
        check_durations(self.elapsed_s, self.timer_s)
        if self.garmin_activity_id is not None and self.garmin_activity_id <= 0:
            raise ValueError("the Garmin id must be positive")
        if self.origin is ActivityOrigin.GARMIN and self.garmin_activity_id is None:
            raise ValueError("an activity downloaded from Garmin has its Garmin id")

    @classmethod
    def from_activity(
        cls,
        activity: Activity,
        archived: ArchivedFile,
        origin: ActivityOrigin,
        imported_at: datetime,
        garmin_activity_id: int | None = None,
    ) -> ActivityRecord:
        """Index row for an activity just read and archived."""
        return cls(
            activity.identity,
            activity.file_format,
            activity.sport,
            activity.start,
            activity.elapsed_s,
            activity.timer_s,
            activity.summary,
            archived,
            origin,
            imported_at,
            garmin_activity_id,
        )
