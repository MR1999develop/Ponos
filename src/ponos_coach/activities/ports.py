IMPLAUSIBLE_RETRY_AFTER_S: Final = 86_400.0  # one day: beyond this, the wait is not taken seriously

# --- Archive of original files -----------------------------------------------------------


class ArchiveError(Exception):
    """Root of the errors of the original-files archive."""


class ArchiveWriteError(ArchiveError):
    """Write failed (disk full, permissions, I/O); nothing remains in the archive."""


class ArchiveFileMissingError(ArchiveError):
    """The indicated file is not in the archive."""


class ArchiveTooLargeError(ArchiveError):
    """The content exceeds the maximum allowed bytes; it was neither read nor written."""


class ArchiveIntegrityError(ArchiveError):
    """The file is there but its SHA-256 or its size are not the recorded ones."""


class ActivityArchive(Protocol):
    """Archive of original files (FIT, GPX), source of truth of the activities.

    The file name is generated by the program, never an external datum. A write is durable
    (temporary file, flush, rename) and idempotent: the same bytes, format and year give
    the same `ArchivedFile` without duplicating anything.
    """

    def store(self, content: bytes, file_format: FileFormat, start: datetime) -> ArchivedFile:
        """Saves the original bytes and returns the relative path, SHA-256 and size.

        `start` (UTC) chooses the year subfolder. At the end the file is durable and the
        caller may write the record in the index.

        Raises:
            ArchiveTooLargeError: more than `MAX_ACTIVITY_FILE_BYTES` bytes.
            ArchiveWriteError: write failed; the archive does not change.
        """
        ...

    def read(self, file: ArchivedFile, max_bytes: int) -> bytes:
        """Content of the file, after verifying size and SHA-256.

        Raises:
            ArchiveFileMissingError: the file is not there.
            ArchiveTooLargeError: the file exceeds `max_bytes` (it is not read beyond).
            ArchiveIntegrityError: size or SHA-256 differ from the recorded ones.
        """
        ...

    def verify(self, file: ArchivedFile) -> None:
        """Checks size and SHA-256 without keeping the file in memory.

        Raises:
            ArchiveFileMissingError: the file is not there.
            ArchiveIntegrityError: size or SHA-256 differ from the recorded ones.
        """
        ...

    def list_orphan_temporaries(self) -> Sequence[PurePosixPath]:
        """Temporaries left by an interrupted write, relative to the archive, sorted."""
        ...

    def remove_orphan_temporaries(self) -> int:
        """Deletes the orphan temporaries; returns how many it removed. Archived files
        are never touched."""
        ...


# --- Activity index -----------------------------------------------------------------


class SyncJournalError(Exception):
    """Root of the errors of the synchronization journal."""


class ActivityIndexError(Exception):
    """Root of the errors of the activity index."""


class DuplicateActivityError(ActivityIndexError):
    """A record with the same identity or the same Garmin id already exists."""


class ActivityNotFoundError(ActivityIndexError):
    """The indicated activity is not in the index."""


class TransactionStateError(ActivityIndexError):
    """Nested transaction: one transaction at a time, per connection."""


class StorageBusyError(ActivityIndexError, SyncJournalError):
    """The database is busy with another process beyond the maximum wait: the transaction has
    not even started, nothing has changed. It can be retried later."""


class ActivityIndex(Protocol):
    """Activity index of a profile (derived from the files, regenerable).

    Every operation outside a transaction is atomic on its own. Inside `transaction()` the
    changes (also of the other stores of the same profile) all take effect or none do.
    """

    def transaction(self) -> AbstractContextManager[None]:
        """Transaction: `with index.transaction(): ...`.

        On normal exit it commits, with an exception it rolls everything back and the exception
        is re-raised. It does not nest (`TransactionStateError`) and does not stay open during
        network or
        user waits.
        """
        ...

    def exists(self, identity: ActivityIdentity) -> bool:
        """True if there is a record with this identity."""
        ...

    def get(self, identity: ActivityIdentity) -> ActivityRecord | None:
        """The record with this identity, or None."""
        ...

    def find_possible_duplicates(
        self, start: datetime, elapsed_s: float
    ) -> Sequence[ActivityRecord]:
        """Records for which `is_possible_duplicate(start, elapsed_s, ...)` is true, by start.

        Used to recognize the same activity that arrived in another format. It does not exclude
        the same identity: the caller checks `exists` first.
        """
        ...

    def add(self, record: ActivityRecord) -> None:
        """Adds a record. The file in the archive must already be durable.

        Raises:
            DuplicateActivityError: identity or Garmin id already present; nothing changes.
        """
        ...

    def list_by_start(self) -> Sequence[ActivityRecord]:
        """All records by ascending start (ties by identity key)."""
        ...

    def find_by_garmin_id(self, garmin_id: GarminActivityId) -> ActivityRecord | None:
        """The record with this Garmin id, or None."""
        ...

    def link_garmin_id(self, identity: ActivityIdentity, garmin_id: GarminActivityId) -> None:
        """Links a Garmin id to an activity already present (matched to one imported from file).

        Idempotent: repeating the same link changes nothing. The record's origin
        does not change (it stays the one with which it entered).

        Raises:
            ActivityNotFoundError: the identity is not in the index.
            DuplicateActivityError: the id already belongs to another record, or this record
            already has
                a different Garmin id; nothing changes.
        """
        ...


# --- Import of files, folders and archives ----------------------------------------------------


class Clock(Protocol):
    """Injected clock: the current instant, in UTC, for `imported_at`."""

    def now(self) -> datetime:
        """Current instant with UTC time zone."""
        ...


class ImportIssue(Enum):
    """Reason why a file does not become an activity. The value is stable.

    The first eight coincide (by value) with `ActivityFileReason`; the others arise before
    decoding (the source) or after it (the profile archive).
    """

    EMPTY = "empty"
    TOO_LARGE = "too_large"
    CORRUPT = "corrupt"
    NOT_AN_ACTIVITY = "not_an_activity"
    UNSUPPORTED_FORMAT = "unsupported_format"
    EXTENSION_MISMATCH = "extension_mismatch"
    TOO_MANY_RECORDS = "too_many_records"
    TOO_LONG = "too_long"
    UNREADABLE = "unreadable"  # vanished, permissions, I/O error
    NOT_REGULAR_FILE = "not_regular_file"  # link, junction, reparse point, FIFO...
    RESERVED_NAME = "reserved_name"  # reserved or invalid name on Windows
    PATH_TOO_LONG = "path_too_long"
    UNSAFE_NAME = "unsafe_name"  # ZIP entry with `..`, absolute path, drive, control characters
    ARCHIVE_INVALID = "archive_invalid"  # corrupt, inconsistent ZIP, with false size or CRC
    ARCHIVE_LIMIT = "archive_limit"  # too many entries, too many bytes, compression ratio
    ENCRYPTED = "encrypted"  # encrypted entry
    NESTED_ARCHIVE = "nested_archive"  # ZIP inside a ZIP
    STORAGE_FAILED = "storage_failed"  # the profile archive could not write


@dataclass(frozen=True, slots=True)
class ImportEntry:
    """An activity file that is a candidate for import, as a source lists it.

    `entry_id` is opaque (assigned by the source), `name` is a displayable name (relative
    path; for a ZIP entry `<zip>!<entry>`) without control characters, `size_bytes`
    the declared size. No external datum ever becomes a path on disk.
    """

    entry_id: int
    name: str
    size_bytes: int


@dataclass(frozen=True, slots=True)
class SkippedEntry:
    """A file or an entry that the source skipped before reading it, with the reason."""

    name: str
    issue: ImportIssue


@dataclass(frozen=True, slots=True)
class ImportScan:
    """Outcome of examining a source: what to import, what skipped, how many entries examined.

    The two sequences are sorted by name (stable order).
    """

    entries: tuple[ImportEntry, ...]
    skipped: tuple[SkippedEntry, ...]
    examined: int


class ImportLimit(Enum):
    """Cap that stops the examination of a source (no partial import)."""

    ACTIVITY_FILES = "activity_files"
    EXAMINED_ENTRIES = "examined_entries"
    DEPTH = "depth"


class ImportSourceError(Exception):
    """Root of the errors of an import source."""


class ImportLimitExceededError(ImportSourceError):
    """The examination exceeded a cap: nothing is imported, a smaller source is needed."""

    def __init__(self, limit: ImportLimit, maximum: int) -> None:
        super().__init__(f"{limit.value}>{maximum}")
        self.limit = limit
        self.maximum = maximum


class ImportScanCancelledError(ImportSourceError):
    """The examination was cancelled by whoever requested it: nothing was imported."""


class ImportSourceUnreadableError(ImportSourceError):
    """The folder or the list of files of the source cannot be read."""


class ImportEntryError(ImportSourceError):
    """A file could not be read (vanished, too large, inconsistent ZIP...)."""

    def __init__(self, issue: ImportIssue) -> None:
        super().__init__(issue.value)
        self.issue = issue


class ImportSource(Protocol):
    """Import source: a list of chosen files or a folder, ZIPs included.

    `scan()` examines without importing (only names and sizes, also the ZIP directories) and
    is called once; `read()` returns the bytes of an already listed file, a ZIP already
    extracted in memory and verified. The source owns its resources: whoever creates it
    closes it with `close()`. It never modifies the original files.
    """

    def scan(self, is_cancelled: Callable[[], bool] | None = None) -> ImportScan:
        """Examines the source.

        `is_cancelled`, if given, is polled continuously during the examination (even inside a
        huge folder or a ZIP with many entries); as soon as it is true the examination stops.

        Raises:
            ImportScanCancelledError: `is_cancelled` became true.
            ImportLimitExceededError: over 50,000 activity files, 500,000 examined entries or
                32 levels of subfolders.
            ImportSourceUnreadableError: the folder cannot be read.
        """
        ...

    def read(self, entry: ImportEntry, max_bytes: int) -> bytes:
        """Bytes of the file, no more than `max_bytes`.

        Raises:
            ImportEntryError: the file cannot be read or is too large (`issue` says why).
        """
        ...

    def close(self) -> None:
        """Releases the resources; can be called more than once."""
        ...


# --- Synchronization journal -------------------------------------------------------------


class UnknownJournalEntryError(SyncJournalError):
    """The entry is not in the journal."""


class SyncJournal(Protocol):
    """Synchronization journal of a profile: cursors and state of each remote activity.

    It lives on the same connection and in the same transaction as the index
    (`ActivityIndex.transaction()`): the state of an entry and the resulting activity are
    committed together. Outside a transaction each operation is atomic on its own.
    """

    def load_cursor(self, kind: ListingKind) -> ListingCursor | None:
        """The saved cursor for that list, or None if it never started."""
        ...

    def save_cursor(self, kind: ListingKind, cursor: ListingCursor) -> None:
        """Saves (replaces) the list cursor."""
        ...

    def known_ids(self, ids: Collection[GarminActivityId]) -> frozenset[GarminActivityId]:
        """Among the given `ids`, those that have an entry in the journal, in any state."""
        ...

    def add_pending(self, items: Sequence[RemoteActivity], now: datetime) -> int:
        """Adds a `PENDING` entry for each activity the journal does not know yet.

        Idempotent by Garmin id: existing entries do not change (neither state nor summary).
        Returns how many new entries it added. `now` is UTC to the millisecond.
        """
        ...

    def next_to_process(self, limit: int) -> Sequence[JournalEntry]:
        """At most `limit` entries to process (`PENDING` and `RETRYABLE`).

        Stable order: activity start from most recent, ties by descending Garmin id.

        Raises:
            ValueError: `limit` less than 1.
        """
        ...

    def next_exhausted(self, limit: int) -> Sequence[JournalEntry]:
        """At most `limit` entries failed for `ATTEMPTS_EXHAUSTED`, same order as
        `next_to_process`. They serve the "Full check", which rearms them with
        `rearm_exhausted`.

        Raises:
            ValueError: `limit` less than 1.
        """
        ...

    def get(self, garmin_id: GarminActivityId) -> JournalEntry | None:
        """The entry with this id, or None."""
        ...

    def update(self, entry: JournalEntry) -> None:
        """Moves the entry with the same id to the new state (state, attempts, cause, instant).

        The remote summary of the entry does not change.

        Raises:
            UnknownJournalEntryError: the id is not in the journal.
            InvalidTransitionError: the current state does not allow the new one (`can_transition`);
                nothing changes.
        """
        ...

    def counts(self) -> Mapping[SyncStatus, int]:
        """How many entries there are per state; every state is present, even with 0."""
        ...

    def last_completed_at(self) -> datetime | None:
        """When the last synchronization finished (UTC), or None if none has finished."""
        ...

    def record_completed(self, when: datetime) -> None:
        """Marks the end of a synchronization (UTC, to the millisecond)."""
        ...


# --- Garmin: list and originals, account ---------------------------------------------------


class ActivitySourceError(Exception):
    """Root of the errors coming from Garmin (list, download, login).

    The subclasses are distinct only where the caller's reaction changes. No message
    contains tokens, passwords, Garmin responses or health data.
    """


class AuthenticationRequiredError(ActivitySourceError):
    """Tokens are missing, expired or revoked: a new login is needed."""


class RateLimitedError(ActivitySourceError):
    """Garmin limits the rate (HTTP 429): slow down, then retry with backoff.

    `retry_after_s` is the wait suggested by Garmin (`Retry-After`), if it gives one: always `None`
    or a finite, non-negative number not above `IMPLAUSIBLE_RETRY_AFTER_S`. A negative value,
    NaN or infinite, or larger than the maximum, becomes `IMPLAUSIBLE_RETRY_AFTER_S`: a wait
    that no cap accepts, so the caller stops with a clear outcome instead of
    raising or sleeping for a long time. (The Garmin adapter already discards unreadable headers:
    no suggestion, `None`.)
    """

    def __init__(self, retry_after_s: float | None = None) -> None:
        super().__init__("rate limited")
        if retry_after_s is None:
            self.retry_after_s: float | None = None
        elif math.isfinite(retry_after_s) and 0 <= retry_after_s <= IMPLAUSIBLE_RETRY_AFTER_S:
            self.retry_after_s = retry_after_s
        else:
            self.retry_after_s = IMPLAUSIBLE_RETRY_AFTER_S


class TransientSourceError(ActivitySourceError):
    """Error that may pass: network, timeout, 5xx, truncated response. Retried with backoff."""


class ServiceUnavailableError(TransientSourceError):
    """Garmin does not respond or is not reachable (also at login)."""


class DefinitiveSourceError(ActivitySourceError):
    """Retrying would give the same outcome: original absent (404, 410), rejected, response
    not interpretable."""


class DownloadTooLargeError(DefinitiveSourceError):
    """The download exceeds the maximum bytes: it was interrupted, nothing was kept."""


class ActivitySource(Protocol):
    """An authenticated session with Garmin that lists and downloads a user's activities.

    Each call has its own timeout (set by the adapter): no unbounded wait. Pauses
    and retries are not here, they belong to the caller (`SyncPolicy`). External inputs
    (JSON, bytes) are already transformed into domain types or errors.
    """

    def list_page(self, offset: int, limit: int) -> ActivityPage:
        """A page of the list, from the most recent activities.

        `limit` is between 1 and `MAX_PAGE_SIZE`. Malformed entries are discarded and counted in
        `raw_count`; `declared_total` is the total if Garmin gives it.

        Raises:
            AuthenticationRequiredError, RateLimitedError, TransientSourceError,
            DefinitiveSourceError: see the classes.
        """
        ...

    def download_original(self, activity_id: GarminActivityId, max_bytes: int) -> bytes:
        """The bytes of the original as Garmin gives them: a ZIP with a FIT, a GPX or other.

        It does not interpret the content (the import does). It stops at `max_bytes` without
        keeping the
        rest in memory.

        Raises:
            DownloadTooLargeError: more than `max_bytes` bytes.
            AuthenticationRequiredError, RateLimitedError, TransientSourceError,
            DefinitiveSourceError: see the classes.
        """
        ...


class GarminAccountError(ActivitySourceError):
    """Root of the login errors."""


class InvalidCredentialsError(GarminAccountError):
    """Email or password rejected by Garmin."""


class MfaCancelledError(GarminAccountError):
    """The user cancelled the MFA code request: nothing was saved."""


@dataclass(frozen=True, slots=True)
class GarminSession:
    """An authenticated session and the tokens to resume it.

    `tokens` are those to save in the keyring (they may have been renewed compared to
    those with which the session was resumed).
    """

    source: ActivitySource
    tokens: SessionTokens


class GarminAccount(Protocol):
    """Login to Garmin and resumption of a session from saved tokens.

    The password goes only to this port and is neither saved nor logged. Each call has a
    timeout.
    """

    def login(
        self, email: str, password: str, prompt_mfa_code: Callable[[], str | None]
    ) -> GarminSession:
        """Logs in with email and password; if MFA is needed it calls `prompt_mfa_code`.

        `prompt_mfa_code` returns the typed code, or None if the user cancels. It must be
        called at most a few times (adapter limit).

        Raises:
            InvalidCredentialsError: credentials rejected (also wrong MFA code).
            MfaCancelledError: `prompt_mfa_code` returned None.
            RateLimitedError: Garmin limits the rate.
            ServiceUnavailableError: Garmin does not respond.
        """
        ...

    def resume(self, tokens: SessionTokens) -> GarminSession:
        """Resumes the session from the saved tokens, without a password.

        Raises:
            AuthenticationRequiredError: tokens expired, revoked or not recognized.
            RateLimitedError, ServiceUnavailableError: as for `login`.
        """
        ...
